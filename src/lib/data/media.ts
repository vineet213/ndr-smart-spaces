/* generated media read model --------------------------------------------- */

/**
 * Widened view over the generated media module. The generated union covers the
 * media-kit records today and grows with the press-archive records the CMS
 * seeds; the derivation below reads either shape without depending on the
 * current on-disk export.
 */
type CmsMediaRecord = {
  id: string;
  status: string;
  folder: string;
  ref?: string;
  label?: string;
  caption?: string;
  format?: string;
  classification?: string;
  revision?: string;
  date?: string;
  category?: string;
  recordStatus?: string;
  publication?: string;
  image?: string;
  href?: string;
  external?: boolean;
};

const cmsMediaRecords = cmsMedia as unknown as readonly CmsMediaRecord[];

