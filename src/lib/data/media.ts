export type MediaKitItemStatus = "available" | "pending";

export type MediaKitItem = {
  ref: string;
  label: string;
  note: string;
  format: string;
  classification: string;
  revision: string;
  status: MediaKitItemStatus;
};

const cmsMediaKit: readonly MediaKitItem[] = (() => {
  const result: MediaKitItem[] = [];
  for (const record of cmsMediaRecords) {
    if (record.folder !== "media-kit") continue;
    result.push({
      ref: record.ref ?? "",
      label: record.label ?? "",
      note: record.caption ?? "",
      format: record.format ?? "",
      classification: record.classification ?? "",
      revision: record.revision ?? "",
      status: record.status as MediaKitItemStatus,
    });
  }
  return result;
})();

