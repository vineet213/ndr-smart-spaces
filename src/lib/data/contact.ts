/* office directory -------------------------------------------------------- */

export type ContactOffice = {
  key: string;
  kind: string;
  name: string;
  lines: readonly string[];
  phone: string;
  email: { label: string; href: string };
  hours: string;
  directions?: { label: string; href: string; external: boolean };
};

const cmsOffices: readonly ContactOffice[] = cmsDirectory.map((entry) => ({
  key: entry.key,
  kind: entry.kind,
  name: entry.name,
  lines: entry.lines.map((line) => line.value),
  phone: entry.phone,
  email: { label: entry.email.label, href: entry.email.href },
  hours: entry.hours,
  ...("directions" in entry
    ? { directions: entry.directions as { label: string; href: string; external: boolean } }
    : {}),
}));

